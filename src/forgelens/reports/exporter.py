class ReportExporter:
    """Exports AuditResult objects into JSON, Markdown, and HTML reports."""

    @staticmethod
    def export_json(audit_result: AuditResult) -> str:
        data = audit_result.model_dump()
        sanitized = redact_sensitive_keys(data)
        return json.dumps(sanitized, ensure_ascii=False, indent=2)

    @staticmethod
    def export_markdown(audit_result: AuditResult) -> str:
        sanitized_dict = redact_sensitive_keys(audit_result.model_dump())
        template = Template(MARKDOWN_TEMPLATE)
        return template.render(audit=sanitized_dict)

    @staticmethod
    def export_html(audit_result: AuditResult) -> str:
        sanitized_dict = redact_sensitive_keys(audit_result.model_dump())
        template = Template(HTML_TEMPLATE)
        return template.render(audit=sanitized_dict)
