"""Report exporter engine supporting JSON, Markdown, and HTML formats with token redaction."""

import json
import re
from typing import Any, Dict
from jinja2 import Template

from forgelens.audit.engine import AuditResult


def redact_sensitive_keys(data: Any) -> Any:
    """Recursively redacts API keys and tokens from report data structures."""
    if isinstance(data, str):
        # Redact patterns resembling API keys (e.g. sk-..., hf_...)
        redacted = re.sub(r"sk-[a-zA-Z0-9_-]{20,}", "sk-***REDACTED***", data)
        redacted = re.sub(r"hf_[a-zA-Z0-9_-]{20,}", "hf_***REDACTED***", redacted)
        return redacted
    elif isinstance(data, dict):
        new_dict = {}
        for k, v in data.items():
            if any(term in k.lower() for term in ["key", "token", "secret", "auth", "password"]):
                new_dict[k] = "***REDACTED***"
            else:
                new_dict[k] = redact_sensitive_keys(v)
        return new_dict
    elif isinstance(data, list):
        return [redact_sensitive_keys(item) for item in data]
    return data


